// Eight 24×24 creature templates. Twenty-five named enemies and bosses are
// built from these by palette swap (see ENEMY_ART in enemies.js) — the same
// trick the generator icons use, for the same reason.
//
// Palette slots: o outline, 1 dark, 2 mid, 3 light, 4 accent, e eye, w glint.
// tests/content.test.js enforces that every grid is rectangular and that every
// palette covers every character its shape uses.

